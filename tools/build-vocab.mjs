// Builds src/data/vocabulary.json from docs/glossary.md, so the public example
// vocabulary can never drift from the glossary (check C-12). Every term is
// recorded as draft, drafted with AI assistance, review level unknown: that is
// the truth about this glossary until a person reviews it.
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

export function buildVocabulary(glossaryText) {
  const rows = glossaryText.split("\n").filter((l) => l.startsWith("| ") && !l.startsWith("| Term") && !l.startsWith("|---"));
  const terms = rows.map((l, i) => {
    const [label, definition] = l.trim().replace(/^\||\|$/g, "").split("|").map((x) => x.trim());
    return {
      term_id: `NDL-GLO-${String(i + 1).padStart(3, "0")}`,
      preferred_label: label,
      alt_labels: "",
      definition,
      status: "draft",
      drafted_by: "ai-assisted",
      review_level: "unknown",
      provenance: "docs/glossary.md, ndl-pubsec-mcp",
      semantic_bindings: ""
    };
  });
  return {
    about:
      "The public example vocabulary for term_lookup: this repository's own glossary (docs/glossary.md), generated by tools/build-vocab.mjs. Drafted with AI assistance and not yet reviewed, so every term is draft and review level unknown. Point NDL_MCP_VOCAB_PATH at a governed register (for example the R2 vocabulary) to use real certified terms; that file is never copied into this repository.",
    source: "docs/glossary.md",
    terms
  };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = join(dirname(fileURLToPath(import.meta.url)), "..");
  const out = buildVocabulary(readFileSync(join(root, "docs/glossary.md"), "utf8"));
  writeFileSync(join(root, "src/data/vocabulary.json"), JSON.stringify(out, null, 2) + "\n");
  console.log(`vocabulary built: ${out.terms.length} terms`);
}
